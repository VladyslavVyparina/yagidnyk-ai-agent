export function buildSystemPrompt(knowledgeBaseSnippet?: string): string {
  const today = new Date().toLocaleDateString("uk-UA", { year: "numeric", month: "long", day: "numeric" });
  return [
    SYSTEM_PROMPT,
    `\n[КОНТЕКСТ БІЗНЕСУ]\n${BUSINESS_CONTEXT}`,
    `\nСьогоднішня дата: ${today}.`,
    knowledgeBaseSnippet ? `\n[ФРАГМЕНТИ БАЗИ ЗНАНЬ, релевантні поточному запиту]\n${knowledgeBaseSnippet}` : "",
  ].join("\n");
}
